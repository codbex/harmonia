// Generates dist/harmonia-extend.css, the Tailwind CSS v4 entry a consuming
// project imports to compile the utility classes Harmonia does NOT ship.
//
// harmonia.css safelists a curated Tailwind subset via `@source inline(...)`.
// A project that needs something outside it (say `md:size-6`) would otherwise
// have to run its own full Tailwind build, duplicating preflight, the design
// tokens and the whole safelisted subset. The generated entry solves that with
// two halves:
//
//   - the theme Harmonia adds on top of Tailwind's (its semantic color tokens,
//     radius and shadow scales, the extra font sizes and containers) plus its
//     custom variants, so a class like `md:bg-primary` or `dark:text-2xs`
//     resolves exactly as it does inside the library. The token *values* are not
//     copied: the theme maps them to `var(--primary)` and friends, so
//     harmonia.css stays the only place they are defined and a custom theme
//     keeps working.
//   - every `@source inline(...)` pattern mirrored as `@source not inline(...)`,
//     Tailwind's exact-match candidate blocklist, so nothing harmonia.css
//     already ships is generated a second time. Mirroring the patterns verbatim
//     means Tailwind's own brace/range expander decides what they cover, so the
//     blocklist can never drift from the safelist.
//
// Everything else is dropped: the `@source` globs (they would scan Harmonia's
// own sources), `@import "tailwindcss"`, `@layer base`, the `:root` / `.dark`
// token blocks, the component stylesheets and the plain class rules. Harmonia's
// `@utility` blocks are deliberately left out too - they `@apply` safelisted
// classes, which are blocklisted here, and applying a blocklisted class is a
// hard error.
//
// Dropping the `:root` values also keeps the entry strictly additive. Copying
// them into a `@theme` would shadow Tailwind's own inlined `--radius` /
// `--shadow` / `--blur` aliases, and a bare `rounded` would then come out at
// Harmonia's radius instead of the 0.25rem harmonia.css already ships for it.
//
// Input is src/styles/globals.css with its local `@import`s inlined, so a new
// stylesheet under src/styles/ is picked up automatically.
//
// Run with `npm run extend-css:generate`. It runs on `npm run build:prod` (the
// publish path) but NOT on `npm run build`: nothing in the library, the docs or
// the tests reads the artifact, so there is no reason to spend the time on it
// during development.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENTRY = path.join(ROOT, 'src', 'styles', 'globals.css');
const OUT_FILE = path.join(ROOT, 'dist', 'harmonia-extend.css');

const HEADER = `/* AUTO-GENERATED by scripts/generate-extend-css.cjs from src/styles/*.css. Do not edit by hand. */
/*
 * Tailwind CSS v4 entry for the utility classes Harmonia does not ship.
 *
 * Import it from your own stylesheet, declare what you need, and compile with
 * the Tailwind CLI:
 *
 *   @import "@codbex/harmonia/dist/harmonia-extend.css";
 *   @source inline("md:size-6");        -- an explicit list of classes, or
 *   @source "./src";                   -- scan a folder for the classes it uses
 *
 *   npx @tailwindcss/cli -m -i extend.css -o extend.css
 *
 * Load the result AFTER harmonia.css - both land in the same cascade layer, so
 * a generated \`md:size-6\` only wins over Harmonia's \`size-6\` when it comes
 * later. The output holds only the missing classes; everything harmonia.css
 * already ships is blocklisted at the bottom of this file.
 *
 * Do not \`@apply\` a class Harmonia ships (\`p-4\`, \`flex\`, ...) in that
 * stylesheet: a blocklisted class cannot be applied and Tailwind will fail with
 * "explicitly disabled". Use the class in your markup instead.
 */`;

const THEME_NOTE = `/* Tailwind's default theme has to be the first \`@theme\` in the file. Tailwind
   emits one consolidated \`:root\` rule where it finds it, so this keeps every
   emitted token inside \`@layer theme\`, where harmonia.css's unlayered \`:root\`
   still wins - no duplicated tokens, no self-referential \`var()\` cycles and no
   overriding of \`.dark\`.

   That rule is expected to hold a few tokens: Tailwind emits every default-theme
   key a generated utility actually reads. \`--spacing\` is the one a consumer sees
   most often, since any spacing-derived class (\`h-80\`, \`gap-20\`, \`md:pt-12\`)
   compiles to \`calc(var(--spacing) * n)\` and marks the key used. Seeing it in the
   output is not a duplicate of Harmonia's own token - it is Tailwind's value, in
   the weakest layer, losing to harmonia.css at runtime.

   The import is deliberately NOT \`reference\`. Suppressing the emission would
   also suppress the default-theme vars Harmonia does not ship, and a consumer's
   \`bg-lime-500\` would then reference a \`--color-lime-500\` that nothing defines.

   \`source(none)\` turns off automatic source detection, which would otherwise
   scan the whole working directory: the output then holds exactly what the
   importing stylesheet asks for, and nothing else. */`;

const BLOCKLIST_NOTE = `/* Harmonia's public utility subset, copied verbatim from the safelist so
   Tailwind's own expander covers exactly the same classes. A blocklist entry is
   an exact class name, so \`md:p-4\` is still generated even though \`p-4\` is
   listed. */`;

const SHIPPED_NOTE = `/* The classes the components themselves use. The safelist above is the public
   subset, not everything harmonia.css contains: the build also scans src/ and
   emits whatever it finds there, so those classes have to be excluded too. This
   list is the scan of src/ filtered down to the candidates that really compile,
   which is by definition what harmonia.css ships. */`;

// Resolve an `@import` the way the Tailwind CLI does: `.`-relative against the
// importing file, bare specifiers through node resolution. Only the flattened
// stylesheet's `@import "tailwindcss"` reaches the bare branch.
function loadStylesheet(id, base) {
  const file = id.startsWith('.') ? path.join(base, id) : require.resolve(id.endsWith('.css') ? id : `${id}/index.css`);
  return Promise.resolve({ path: file, base: path.dirname(file), content: fs.readFileSync(file, 'utf8') });
}

// The classes harmonia.css ships beyond its safelist, i.e. the ones its own
// build finds by scanning src/. Both halves come from Tailwind itself so this
// can never disagree with what `npm run tailwind` produces: `compile()` yields
// the normalized `@source` list the CLI feeds the scanner, and the design system
// says which of the scanned strings are really utilities (`candidatesToCss`
// returns null for the rest). Filtering matters in both directions - an unused
// scanner hit like a bare identifier must NOT be blocklisted, since a consumer
// may well define an `@utility` of that name.
async function collectShippedClasses(css) {
  const { compile, __unstable__loadDesignSystem } = require('tailwindcss');
  const { Scanner } = require('@tailwindcss/oxide');
  const options = { base: path.dirname(ENTRY), loadStylesheet };
  const { sources } = await compile(css, options);
  const candidates = new Scanner({ sources }).scan();
  const designSystem = await __unstable__loadDesignSystem(css, options);
  const compiled = designSystem.candidatesToCss(candidates);
  // A `{` or `}` in a candidate would be read as a brace pattern by
  // `@source not inline(...)`, so leave those out - the cost is a duplicate
  // rule, never a wrongly excluded class.
  return candidates.filter((candidate, i) => compiled[i] !== null && !/[{}]/.test(candidate)).sort();
}

// Inline every local `@import "./x.css";` so the flattened text keeps source
// order (a token declared in an imported file precedes globals.css's own).
function flatten(file) {
  const dir = path.dirname(file);
  return fs.readFileSync(file, 'utf8').replace(/^@import\s+"(\.[^"]*)"\s*;[ \t]*\n?/gm, (_match, rel) => flatten(path.join(dir, rel)));
}

// Index of the `}` closing the block that opens at `open`. Quote- and
// comment-aware so a brace inside a string or a comment does not count.
function matchBrace(css, open) {
  let depth = 0;
  let quote = null;
  for (let i = open; i < css.length; i++) {
    const ch = css[i];
    if (quote) {
      if (ch === '\\') i++;
      else if (ch === quote) quote = null;
    } else if (ch === '"' || ch === "'") {
      quote = ch;
    } else if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2);
      i = end === -1 ? css.length : end + 1;
    } else if (ch === '{') {
      depth++;
    } else if (ch === '}' && --depth === 0) {
      return i;
    }
  }
  return -1;
}

// Split the top level of a stylesheet into statements (`{ prelude, body: null }`,
// e.g. `@source inline("...")`) and blocks (`{ prelude, body }`), dropping
// comments. Quote- and paren-aware, so the braces inside an `@source inline()`
// pattern are not mistaken for a block.
function parseTopLevel(css) {
  const nodes = [];
  let i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) {
      const end = css.indexOf('*/', i + 2);
      i = end === -1 ? css.length : end + 2;
      continue;
    }
    if (/\s/.test(css[i])) {
      i++;
      continue;
    }
    const start = i;
    let parens = 0;
    let quote = null;
    while (i < css.length) {
      const ch = css[i];
      if (quote) {
        if (ch === '\\') i++;
        else if (ch === quote) quote = null;
      } else if (ch === '"' || ch === "'") {
        quote = ch;
      } else if (css.startsWith('/*', i)) {
        const end = css.indexOf('*/', i + 2);
        i = end === -1 ? css.length : end + 1;
      } else if (ch === '(') {
        parens++;
      } else if (ch === ')') {
        parens--;
      } else if (parens === 0 && (ch === '{' || ch === ';')) {
        break;
      }
      i++;
    }
    if (i >= css.length) break;
    const prelude = css.slice(start, i).trim();
    if (css[i] === ';') {
      nodes.push({ prelude, body: null });
      i++;
      continue;
    }
    const close = matchBrace(css, i);
    if (close === -1) throw new Error(`generate-extend-css: unbalanced block for \`${prelude}\``);
    nodes.push({ prelude, body: css.slice(i + 1, close) });
    i = close + 1;
  }
  return nodes;
}

const quotePattern = (pattern) => (pattern.includes('"') ? `'${pattern}'` : `"${pattern}"`);

// One `@source not inline(...)` per line, several class names per statement
// (space-separated patterns are allowed), wrapped so the file stays readable.
function blocklistLines(classes, width = 160) {
  const lines = [];
  let batch = [];
  const flush = () => {
    if (batch.length) lines.push(`@source not inline(${quotePattern(batch.join(' '))});`);
    batch = [];
  };
  for (const cls of classes) {
    if (batch.length && batch.join(' ').length + cls.length + 1 > width) flush();
    batch.push(cls);
  }
  flush();
  return lines;
}

// Flattened stylesheet -> the extend entry. `shipped` is the extra class list
// from collectShippedClasses(); it is passed in rather than looked up so this
// stays a pure, synchronous transform.
function transform(css, shipped = []) {
  const parts = [];
  const patterns = [];

  for (const { prelude, body } of parseTopLevel(css)) {
    if (body === null) {
      const inlineSource = /^@source\s+(not\s+)?inline\(\s*(['"])([\s\S]*?)\2\s*\)$/.exec(prelude);
      // A pattern harmonia.css already excludes stays available here.
      if (inlineSource) {
        if (!inlineSource[1]) patterns.push(inlineSource[3]);
      } else if (/^@custom-variant\b/.test(prelude)) {
        parts.push(`${prelude};`);
      }
    } else if (/^@theme\b/.test(prelude)) {
      // An `inline` block's values are substituted into the utilities, so its
      // variables are never read at runtime: `reference` keeps them out of the
      // output. A plain block's utilities do read `var(--key)`, so it is copied
      // as-is and Tailwind emits the keys that end up used.
      const params = /\binline\b/.test(prelude) ? `${prelude} reference` : prelude;
      parts.push(`${params} {${body.replace(/\s*$/, '\n')}}`);
    }
  }

  if (!parts.length || !patterns.length) throw new Error('generate-extend-css: no @theme block or safelist pattern found in src/styles');

  const out = [
    HEADER,
    '',
    '@layer theme, base, components, utilities;',
    '',
    THEME_NOTE,
    '@import "tailwindcss/theme.css" layer(theme);',
    '@import "tailwindcss/utilities.css" layer(utilities) source(none);',
    '',
    ...parts.flatMap((part) => [part, '']),
    BLOCKLIST_NOTE,
    ...patterns.map((pattern) => `@source not inline(${quotePattern(pattern)});`),
    '',
    SHIPPED_NOTE,
    ...blocklistLines(shipped),
  ];
  return `${out.join('\n')}\n`;
}

async function main() {
  const source = flatten(ENTRY);
  const shipped = await collectShippedClasses(source);
  const css = transform(source, shipped);
  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, css);
  const safelisted = (source.match(/@source\s+inline\(/g) || []).length;
  console.log(`generate-extend-css: wrote dist/harmonia-extend.css (${safelisted} safelist patterns + ${shipped.length} classes used by the components)`);
}

module.exports = { transform, flatten, parseTopLevel, collectShippedClasses, ENTRY, OUT_FILE };

if (require.main === module) main();
